import { getCompanyDeadlines } from '../directorDeadlines';

describe('standard company deadlines', () => {
  // Hand-derived from HMRC CTM01800 and CTM93040: first of month ten for month ends,
  // and the corresponding date (or February month end) in the following year for filing.
  it.each([
    ['1999-07-01', '2000-04-02', '2000-07-01'],
    ['2026-01-31', '2026-11-01', '2027-01-31'],
    ['2026-02-28', '2026-12-01', '2027-02-28'],
    ['2026-03-31', '2027-01-01', '2027-03-31'],
    ['2026-04-30', '2027-02-01', '2027-04-30'],
    ['2026-05-31', '2027-03-01', '2027-05-31'],
    ['2026-06-30', '2027-04-01', '2027-06-30'],
    ['2026-07-31', '2027-05-01', '2027-07-31'],
    ['2026-08-31', '2027-06-01', '2027-08-31'],
    ['2026-09-30', '2027-07-01', '2027-09-30'],
    ['2026-10-31', '2027-08-01', '2027-10-31'],
    ['2026-11-30', '2027-09-01', '2027-11-30'],
    ['2026-12-31', '2027-10-01', '2027-12-31'],
    ['2026-05-30', '2027-03-01', '2027-05-30'],
    ['2026-05-28', '2027-03-01', '2027-05-28'],
    ['2027-05-28', '2028-02-29', '2028-05-28'],
    ['2027-05-29', '2028-03-01', '2028-05-29'],
    ['2027-02-28', '2027-12-01', '2028-02-29'],
    ['2024-02-28', '2024-11-29', '2025-02-28'],
    ['2024-02-29', '2024-12-01', '2025-02-28'],
    ['2023-07-01', '2024-04-02', '2024-07-01'],
    ['9998-12-30', '9999-10-01', '9999-12-30'],
  ])('uses %s exactly, giving payment %s and filing %s', (end, payment, filing) => {
    expect(getCompanyDeadlines(end)).toEqual({
      periodEnd: new Date(`${end}T00:00:00Z`),
      payment: new Date(`${payment}T00:00:00Z`),
      filing: new Date(`${filing}T00:00:00Z`),
    });
  });

  it.each([
    '',
    '06-30',
    '2026-12',
    '2026-2-01',
    '2026-00-01',
    '2026-13-01',
    '2026-01-00',
    '2026-01-32',
    '2026-04-31',
    '2026-02-29',
    '2100-02-29',
    '2026-12-31\n',
    '1999-06-30',
    '9998-12-31',
  ])('withholds dates for %j', (end) => {
    expect(getCompanyDeadlines(end)).toBeNull();
  });
});
